# Five Real-Life Examples of Machine Learning

# 1. Email Spam Detection
#   * Type: Supervised Learning
#   * Why: The algorithm is trained on a dataset of emails already labeled as "spam" or "not spam", learning to map features of incoming messages to those known labels.

# 2. Credit Card Fraud Detection
#   * Type: Supervised Learning
#   * Why: It uses historical transaction data tagged explicitly as fraudulent or legitimate to train a model that flags suspicious activity in real time.

# 3. Customer Segmentation for E-Commerce
#   * Type: Unsupervised Learning
#   * Why: The system analyzes raw, unlabeled customer purchase behavior and automatically groups shoppers with similar habits into distinct clusters without predefined categories.

# 4. Movie and Music Recommendation Systems
#   * Type: Unsupervised Learning (often paired with collaborative filtering)
#   * Why: It discovers hidden patterns and groupings among user viewing or listening histories to suggest content without relying on pre-assigned tags.

# 5. House Price Prediction
#   * Type: Supervised Learning
#   * Why: The model learns a regression function from a dataset containing historical housing attributes paired with known, final sale prices.

